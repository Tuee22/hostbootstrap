"""The thin pre-binary bootstrapper.

The Python layer does only what must run *before any project binary exists*
(see ``DEVELOPMENT_PLAN/development_plan_standards.md`` §§ M, N):

1. derive the project name from the project's single Cabal file;
2. assert the fail-fast host minimums;
3. ensure the host Haskell build toolchain and package index (Homebrew -> ``ghcup``
   -> GHC/Cabal on Apple silicon; ``ghcup`` -> GHC/Cabal on Linux; a
   PowerShell-downloaded GHCup -> GHC/Cabal on Windows) -- the prerequisites to
   *build* the binary;
4. build the project binary **host-native** at ``./.build/<executable>`` on every
   substrate;
5. ``exec`` the binary, handing control to ``hostbootstrap-core``'s command tree
   extended by the project.

Python does not read, write, *or* initialize Dhall -- the binary owns its config.
A normal command fails fast (exit 1) when no sibling ``<project>.dhall`` exists;
the config is created by an explicit ``project init`` or generated by the test
harness. Ensuring Docker, building the project container, writing/decoding config,
and applying the budget cordon are the project binary's job once it is running.
"""

