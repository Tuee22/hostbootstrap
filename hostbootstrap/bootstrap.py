class ToolchainStep(NamedTuple):
    """A single toolchain-ensure step: a quiet *probe* and its *install* fallback."""

    probe: tuple[str, ...]
    install: tuple[str, ...]


def toolchain_ensure_steps(sub: Substrate) -> tuple[ToolchainStep, ...]:
    """The host build-toolchain ensure steps (development_plan_standards.md § N), run before the build."""
    ghcup = _WINDOWS_GHCUP if sub.is_windows else _GHCUP
    ghcup_steps = (
        ToolchainStep(
            probe=(ghcup, "whereis", "ghc", GHC_VERSION),
            install=(ghcup, "install", "ghc", GHC_VERSION, "--set"),
        ),
        ToolchainStep(
            probe=(ghcup, "whereis", "cabal"),
            install=(ghcup, "install", "cabal", "--set"),
        ),
    )
    if sub.name is SubstrateName.APPLE_SILICON:
        return (
            ToolchainStep(
                probe=(_GHCUP, "--version"),
                install=(_BREW, "install", "ghcup"),
            ),
            *ghcup_steps,
        )
    if sub.is_windows:
        return (
            ToolchainStep(
                probe=(_WINDOWS_GHCUP, "--version"),
                install=(),
            ),
            *ghcup_steps,
        )
    # Linux (linux-cpu / linux-gpu): bootstrap ghcup via its POSIX installer first,
    # mirroring the Apple/Windows shape so a pristine host is not assumed to ship it.
    return (
        ToolchainStep(
            probe=(_GHCUP, "--version"),
            install=(),
        ),
        *ghcup_steps,
    )


def native_build_command(
    spec: ProjectBuildSpec, project_root: Path, *, offline: bool = False
) -> tuple[str, ...]:
    """Build the project binary host-native, in place."""
    cabal = _WINDOWS_CABAL if os.name == "nt" else _CABAL
    command: tuple[str, ...] = (
        cabal,
        "--store-dir",
        str(project_root / _STORE_DIR),
        "build",
    )
    if offline:
        command += ("--offline",)
    return (*command, f"exe:{spec.executable}")


def cabal_update_command() -> tuple[str, ...]:
    """Refresh Cabal's package index when its local state requires it."""
    cabal = _WINDOWS_CABAL if os.name == "nt" else _CABAL
    return (cabal, "update")


class CabalIndexState(StrEnum):
    MISSING = "missing"
    FRESH = "fresh"
    STALE = "stale"


def cabal_index_path() -> Path:
    """The standard secure Hackage index used by Cabal."""
    configured = os.environ.get("CABAL_DIR")
    cabal_dir = Path(configured) if configured else Path.home() / ".cabal"
    return cabal_dir / "packages" / "hackage.haskell.org" / "01-index.tar"


def cabal_index_state(index: Path, *, now: float | None = None) -> CabalIndexState:
    if not index.is_file():
        return CabalIndexState.MISSING
    current_time = time.time() if now is None else now
    age = max(0.0, current_time - index.stat().st_mtime)
    if age > _CABAL_INDEX_MAX_AGE_SECONDS:
        return CabalIndexState.STALE
    return CabalIndexState.FRESH


def native_listbin_command(spec: ProjectBuildSpec, project_root: Path) -> tuple[str, ...]:
    """Print the built exe's path under ``dist-newstyle/``."""
    cabal = _WINDOWS_CABAL if os.name == "nt" else _CABAL
    return (
        cabal,
        "--store-dir",
        str(project_root / _STORE_DIR),
        "list-bin",
        f"exe:{spec.executable}",
    )


def binary_path(spec: ProjectBuildSpec, project_root: Path) -> Path:
    """The single stable ``./.build/<executable>`` location every consumer execs."""
    suffix = ".exe" if os.name == "nt" else ""
    return project_root / _BUILD_DIR / f"{spec.executable}{suffix}"


def exec_argv(spec: ProjectBuildSpec, project_root: Path, args: tuple[str, ...]) -> tuple[str, ...]:
    """The argv handed to ``os.execv``: the built binary plus trailing args."""
    return (str(binary_path(spec, project_root)), *args)


def _toolchain_env() -> dict[str, str]:
    """Environment that sees tools installed during this bootstrap invocation.

    ghcup installs its shims outside the default PATH mid-bootstrap: under
    ``C:/ghcup/bin`` on Windows and ``~/.ghcup/bin`` (with the cabal/local bins
    alongside) on Apple/Linux, so prepend them here for every substrate.
    """
    env = dict(os.environ)
    if os.name == "nt":
        toolchain_paths: tuple[Path, ...] = _WINDOWS_TOOLCHAIN_PATHS
    else:
        home = Path.home()
        toolchain_paths = (
            home / ".ghcup" / "bin",
            home / ".cabal" / "bin",
            home / ".local" / "bin",
        )
    existing = env.get("PATH", "")
    prefix = os.pathsep.join(str(path) for path in toolchain_paths)
    env["PATH"] = f"{prefix}{os.pathsep}{existing}" if existing else prefix
    return env


