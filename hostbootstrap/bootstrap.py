async def _assert_minimums(sub: Substrate) -> None:
    # One floor for both `run` and `build`: the wrapper asserts only the
    # pre-binary build minimums (see prereqs._run_linux); runtime host
    # preconditions are the binary's `ensure` responsibility.
    await prereqs.run_doctor(sub)


async def _already_present(probe: tuple[str, ...]) -> bool:
    """Whether *probe* reports its tool present."""
    for _attempt in range(6):
        try:
            result = await process.run(probe, quiet=True, env=_toolchain_env())
        except FileNotFoundError:
            return False
        except OSError as exc:
            if os.name == "nt" and getattr(exc, "winerror", None) == 32:
                await asyncio.sleep(5)
                continue
            raise
        return result.ok
    return False


async def _ensure_toolchain(sub: Substrate, *, offline: bool = False) -> None:
    """Ensure the host build toolchain."""
    for step in toolchain_ensure_steps(sub):
        if await _already_present(step.probe):
            continue
        if offline:
            missing = " ".join(step.probe)
            raise RuntimeError(
                f"offline build requires the host build tool to be preinstalled: {missing}"
            )
        if not step.install:
            await _install_verified_ghcup(sub)
            continue
        await process.run_checked(step.install, env=_toolchain_env())


async def _install_verified_ghcup(sub: Substrate) -> None:
    """Retrieve the pinned GHCup binary, verify its SHA-256, then install it."""
    platform_key = "windows" if sub.is_windows else "linux"
    try:
        url, expected_sha256 = _GHCUP_DOWNLOADS[(platform_key, sub.arch)]
    except KeyError as exc:
        raise RuntimeError(f"no pinned GHCup download for {platform_key}/{sub.arch}") from exc

    destination = Path(_WINDOWS_GHCUP) if sub.is_windows else Path.home() / ".ghcup/bin/ghcup"
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="hostbootstrap-ghcup-") as temp_dir:
        downloaded = Path(temp_dir) / destination.name
        command: tuple[str, ...]
        if sub.is_windows:
            command = (
                _POWERSHELL,
                "-NoProfile",
                "-Command",
                f"Invoke-WebRequest -Uri '{url}' -OutFile '{downloaded}'",
            )
        else:
            curl = shutil.which("curl")
            if curl is None:
                raise RuntimeError("curl disappeared after the prerequisite check")
            command = (curl, "--proto", "=https", "--tlsv1.2", "-fsSL", url, "-o", str(downloaded))
        await process.run_checked(command, env=_toolchain_env())
        actual_sha256 = hashlib.sha256(downloaded.read_bytes()).hexdigest()
        if actual_sha256 != expected_sha256:
            raise RuntimeError(
                f"GHCup download digest mismatch: expected {expected_sha256}, got {actual_sha256}"
            )
        if not sub.is_windows:
            downloaded.chmod(0o755)
        shutil.copy2(downloaded, destination)


def _files_identical(left: Path, right: Path) -> bool:
    if not left.is_file() or not right.is_file():
        return False
    if left.stat().st_size != right.stat().st_size:
        return False
    return hashlib.sha256(left.read_bytes()).digest() == hashlib.sha256(right.read_bytes()).digest()


def _copy_if_changed(source: Path, destination: Path) -> bool:
    """Copy *source* only when the stable artifact bytes changed."""
    if _files_identical(source, destination):
        return False
    shutil.copy2(source, destination)
    return True


async def _build_native(
    spec: ProjectBuildSpec, *, project_root: Path, offline: bool = False
) -> None:
    """Build host-native, refreshing only a stale index and copying only changed bytes."""
    binary_path(spec, project_root).parent.mkdir(parents=True, exist_ok=True)
    index_state = cabal_index_state(cabal_index_path())
    if offline and index_state is CabalIndexState.MISSING:
        raise RuntimeError(
            "offline build requires a cached Cabal package index; "
            "run an online build once before retrying with --offline"
        )
    if not offline and index_state is not CabalIndexState.FRESH:
        await process.run_checked(cabal_update_command(), cwd=project_root, env=_toolchain_env())
    try:
        await process.run_checked(
            native_build_command(spec, project_root, offline=offline),
            cwd=project_root,
            env=_toolchain_env(),
        )
    except process.CommandError as exc:
        if offline:
            raise RuntimeError(
                "offline Cabal build could not resolve all inputs from the cached index/store"
            ) from exc
        raise
    located = await process.run_checked(
        native_listbin_command(spec, project_root),
        cwd=project_root,
        quiet=True,
        env=_toolchain_env(),
    )
    _copy_if_changed(Path(located.stdout.strip()), binary_path(spec, project_root))


async def build_binary(
    spec: ProjectBuildSpec, *, project_root: Path, offline: bool = False
) -> Path:
    """Run the pre-binary bootstrap (development_plan_standards.md §§ M, N) and build the binary host-native."""
    sub = substrate.detect()
    await _assert_minimums(sub)
    await _ensure_toolchain(sub, offline=offline)
    await _build_native(spec, project_root=project_root, offline=offline)
    return binary_path(spec, project_root)


async def bootstrap(
    spec: ProjectBuildSpec,
    *,
    project_root: Path,
    args: tuple[str, ...] = (),
    offline: bool = False,
) -> None:
    """Build the project binary host-native, then ``exec`` it with ``args``."""
    sub = substrate.detect()
    await _assert_minimums(sub)
    await _ensure_toolchain(sub, offline=offline)
    await _build_native(spec, project_root=project_root, offline=offline)
    argv = exec_argv(spec, project_root, args)
    _exec_project_binary(argv, project_root)


def _exec_project_binary(argv: tuple[str, ...], project_root: Path) -> None:
    # Run the binary with cwd = the project home so its cwd is deterministic on
    # every substrate, regardless of where the caller invoked ``hostbootstrap``.
    # ``argv[0]`` is absolute (``binary_path`` of the resolved ``project_root``),
    # so the POSIX ``os.chdir``-before-``os.execv`` cannot break the exec.
    if os.name == "nt":
        completed = subprocess.run(list(argv), cwd=project_root, check=False)
        raise SystemExit(completed.returncode)
    os.chdir(project_root)
    os.execv(argv[0], list(argv))  # pragma: no cover
